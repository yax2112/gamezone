#Function to Move Pac-Man and Ghosts
def move():
    """Move pacman and all ghosts."""
    if state['game_over']:
        return

    writer.undo()
    writer.write(state['score'], align="center", font=("Arial", 18, "normal"))

    clear()

    if valid(pacman + aim):
        pacman.move(aim)

    index = offset(pacman)

    if tiles[index] == 1:
        tiles[index] = 2
        state['score'] += 2
        x = (index % 20) * 20 - 200
        y = 180 - (index // 20) * 20
        square(x, y)

    up()
    goto(pacman.x + 10, pacman.y + 10)
    dot(20, 'yellow')

    for point, course in ghosts:
        if valid(point + course):
            point.move(course)
        else:
            options = [
                vector(5, 0),
                vector(-5, 0),
                vector(0, 5),
                vector(0, -5),
            ]

            # Hill Climbing algorithm
            best_option = course
            min_distance = float('inf')

            for option in options:
                new_position = point + option
                if valid(new_position):
                    distance = abs(pacman - new_position)
                    if distance < min_distance:
                        min_distance = distance
                        best_option = option

            course.x = best_option.x
            course.y = best_option.y

        up()
        goto(point.x + 10, point.y + 10)
        dot(20, 'red')

    update()

    for point, course in ghosts:
        if abs(pacman - point) < 20:
            state['game_over'] = True
            game_over_screen()
            return

    ontimer(move, 100)

def change(x, y):
    """Change pacman aim if valid."""
    if valid(pacman + vector(x, y)):
        aim.x = x
        aim.y = y

